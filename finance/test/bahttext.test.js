import { test } from 'node:test';
import assert from 'node:assert/strict';
import { bahtText } from '../src/core/bahttext.js';

test('BAHTTEXT: คำอ่านยอดเงินภาษาไทย (สตางค์เป็นจำนวนเต็ม)', () => {
  const cases = [
    [0, 'ศูนย์บาทถ้วน'], [100, 'หนึ่งบาทถ้วน'], [1100, 'สิบเอ็ดบาทถ้วน'], [2100, 'ยี่สิบเอ็ดบาทถ้วน'], [1000, 'สิบบาทถ้วน'],
    [10100, 'หนึ่งร้อยเอ็ดบาทถ้วน'], [123450, 'หนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์'], [845000, 'แปดพันสี่ร้อยห้าสิบบาทถ้วน'],
    [25, 'ศูนย์บาทยี่สิบห้าสตางค์'], [100000000, 'หนึ่งล้านบาทถ้วน'], [100000100, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [2500000000, 'ยี่สิบห้าล้านบาทถ้วน'], [1234567890, 'สิบสองล้านสามแสนสี่หมื่นห้าพันหกร้อยเจ็ดสิบแปดบาทเก้าสิบสตางค์'],
    [-5000, 'ลบห้าสิบบาทถ้วน'],
  ];
  for (const [satang, text] of cases) assert.equal(bahtText(satang), text, String(satang));
});
